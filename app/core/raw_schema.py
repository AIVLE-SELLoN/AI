# `OR REPLACE` 는 컬럼 이름·순서·타입이 같을 때만 통과하므로, 뷰 정의를 바꾸면 여기서
# `cannot change name of view column` 으로 시끄럽게 막힌다 — 조용히 옛 뷰가 남는 것보다 낫다.
_PG_VOC_DOCUMENT_VIEW = VOC_DOCUMENT_VIEW.replace(
    "CREATE VIEW IF NOT EXISTS", "CREATE OR REPLACE VIEW"
)

_SOURCE_DDL: dict[str, tuple[str, ...]] = {
    raw_db.SQLITE: (CHANNEL_DDL, PRODUCTS_DDL, MAPPED_DATA_DDL, CS_DDL, REVIEWS_DDL, ORDERS_DDL),
    raw_db.POSTGRES: (
        _PG_CHANNEL_DDL,
        _PG_PRODUCTS_DDL,
        _PG_MAPPED_DATA_DDL,
        _PG_CS_DDL,
        _PG_REVIEWS_DDL,
        _PG_ORDERS_DDL,
    ),
}

_CLASSIFIED_DDL: dict[str, tuple[str, ...]] = {
    raw_db.SQLITE: (
        CLASSIFIED_ITEM_DDL,
        CLASSIFIED_ITEM_ASPECT_DDL,
        FAILURE_DDL,
        CURSOR_DDL,
    ),
    raw_db.POSTGRES: (
        _PG_CLASSIFIED_ITEM_DDL,
        _PG_CLASSIFIED_ITEM_ASPECT_DDL,
        _PG_FAILURE_DDL,
        _PG_CURSOR_DDL,
    ),
}

_VOC_DOCUMENT_DDL: dict[str, str] = {
    raw_db.SQLITE: VOC_DOCUMENT_VIEW,
    raw_db.POSTGRES: _PG_VOC_DOCUMENT_VIEW,
}


def create_source_tables(conn) -> None:
    """main server 소유 테이블 + 통합 뷰. **운영에서는 안 불린다** — 목 프로듀서 전용이다.

    `products` 는 `channel` 다음, `mapped_data` 는 `products` 다음이어야 한다(FK 방향).
    다만 **sqlite 에서는 깨지는 곳이 CREATE 가 아니라 적재다** — 부모 테이블이 없어도
    `CREATE TABLE ... REFERENCES` 를 통과시키고 다음 INSERT 에서 터진다. Postgres 는 CREATE
    단계에서 바로 막는다.
    """
    dialect = raw_db.dialect_of(conn)
    for ddl in _SOURCE_DDL[dialect]:
        raw_db.execute_ddl(conn, ddl)
    for stmt in (*SOURCE_INDEXES, PRODUCTS_CHANNEL_PRODUCT_INDEX, MAPPED_DATA_GROUP_INDEX):
        raw_db.execute_ddl(conn, stmt)
    raw_db.execute_ddl(conn, _VOC_DOCUMENT_DDL[dialect])


def create_classified_tables(conn) -> None:
    """AI 노드 소유 테이블 + 우리 읽기 모델. 분류 워커가 부른다. **운영 경로다.**

    뷰도 함께 보장한다 — 워커가 자기가 만들지 않은 DB 에 붙는 경우가 있고(프로듀서 없이
    덤프만 받은 상태) 뷰가 없으면 조회가 통째로 실패한다.

    `IF NOT EXISTS` 라 **이미 있는 테이블은 손대지 않으므로** 호출 전에
    `find_legacy_tables()` 로 먼저 걸러야 한다. 동시 실행은 `raw_db.execute_ddl()` 이
    견딘다 — 워커가 CronJob 이라 겹쳐 뜰 수 있고 진 쪽이 죽으면 무한 재시도가 된다.
    """
    dialect = raw_db.dialect_of(conn)
    for ddl in _CLASSIFIED_DDL[dialect]:
        raw_db.execute_ddl(conn, ddl)
    for stmt in CLASSIFIED_INDEXES:
        raw_db.execute_ddl(conn, stmt)
    raw_db.execute_ddl(conn, _VOC_DOCUMENT_DDL[dialect])


# 구버전 raw DB 판별용 — 테이블마다 "8/7 확정 이후에만 있는" 컬럼 하나. 확정 전 구조로
# 만들어진 DB 가 팀원 로컬에 남아 있는데(`data/` 는 gitignore), 거기 대고
# `create_classified_tables()` 를 불러도 `IF NOT EXISTS` 가 옛 테이블을 그대로 두기 때문에
# 실패가 **한참 뒤 조회 단계**에서 `no such column` 으로 터진다.
#
# **마커는 그 테이블에 가장 나중에 들어온 컬럼이어야 한다.** 판정이 "마커가 없으면 옛것"
# 이라, 컬럼을 추가하고 마커를 안 옮기면 **그 사이 버전의 테이블이 전부 최신으로 통과한다.**
# 실제로 버전 컬럼 2개를 넣으면서 마커가 `prompt_version` 에 남아 있었고, 4컬럼 시절
# 테이블이 `find_legacy_tables() = []` 로 통과한 뒤 `no such column: model_version` 으로
# 죽었다 — 가드가 막으려던 바로 그 자리로 되돌아갔다.
LEGACY_MARKERS: dict[str, str] = {
    "classified_item": "pipeline_version",  # 구: prompt_version 만 있던 4컬럼
    "classification_failure": "item_id",  # 구: event_id PK
    "classification_cursor": "last_inquired_at",  # 구: last_occurred_at / last_event_id
}


# 컬럼만으로는 못 잡는 것 — **유니크 제약**. 컬럼이 다 있어도 이게 없으면 재분류가 같은
# `(item_id, aspect)` 를 중복 적재한다(워커의 "aspect 는 지우고 다시 넣는다" 가 이 제약을
# 전제로 짜여 있다). 없으면 탐지 분자가 부풀고, 그건 **오탐 방향이라 시끄럽지도 않다.**
#
# 우리가 만드는 테이블인데도 가드가 필요한 이유는, 인프라가 낡은 문서로 먼저 세워 뒀으면
# `CREATE TABLE IF NOT EXISTS` 가 조용히 건너뛰고 제약 없는 옛 모양이 남기 때문이다.
REQUIRED_UNIQUE_COLUMNS: dict[str, frozenset[str]] = {
    "classified_item_aspect": frozenset({"item_id", "aspect"}),
}


def find_legacy_tables(conn) -> list[str]:
    """확정 스키마 이전 구조로 남아 있는 AI 소유 테이블 이름. 없으면 빈 리스트.

    두 축을 본다 — `LEGACY_MARKERS` 의 마커 컬럼이 없거나 `REQUIRED_UNIQUE_COLUMNS` 의
    조합이 없으면 옛것이다. 없는 테이블은 대상이 아니다(새로 만들면 되는 정상 상태라,
    "있는데 모양이 옛것"인 경우만 골라낸다).

    스키마 조회를 `raw_db` 에 맡긴다 — 여기서 `PRAGMA` 를 직접 쓰면 **Postgres 에서 이 가드
    자신이 구문 오류로 죽는다.**
    """
    stale = []
    for table, marker in LEGACY_MARKERS.items():
        columns = raw_db.table_columns(conn, table)
        if columns and marker not in columns:
            stale.append(table)

    for table, required in REQUIRED_UNIQUE_COLUMNS.items():
        if table in stale or not raw_db.table_columns(conn, table):
            continue
        if required not in raw_db.unique_column_sets(conn, table):
            stale.append(table)
    return stale
