"""Raw DB 스키마 — 노션 「Raw DB 스키마 확정 (8/7)」 §2 를 그대로 옮긴 DDL.

우리가 정한 규칙이 아니라 확정 문서를 옮겨 적은 것이므로, 문서가 바뀌지 않는 한 이 파일도
바뀌지 않아야 한다.

소유권:
    main server 쓰기 : channel · products · mapped_data · orders · cs · reviews
    AI 노드 쓰기      : classified_item · classified_item_aspect ·
                       classification_failure · classification_cursor

**AI 소유 4개 + `voc_document` 뷰는 운영에서도 우리가 만든다** — `create_classified_tables()`
가 그 경로이고 여기 DDL 을 고치면 운영 스키마가 바뀐다. `create_source_tables()` 만 로컬·목
전용이다(목 파이프라인에서는 `scripts/mock_producer.py` 가 main server 자리를 대신한다).

`scripts/` 가 아니라 core 에 있는 이유는 쓰는 쪽과 읽는 쪽이 갈려 있어서다 — 스크립트에
두면 `app/` 이 import 할 수 없어 집계 쪽이 테이블·뷰 이름을 다시 적게 되고 스키마가 두 벌이
된다.

**DDL 은 백엔드 2종을 갈라서 낸다 — 한쪽으로 통일하지 말 것.** 데모(sqlite)가 그대로 돌아야
하고 운영은 Postgres 다. 문법이 갈리는 곳:

    CREATE VIEW IF NOT EXISTS   →  CREATE OR REPLACE VIEW   (Postgres 에 IF NOT EXISTS 없음)
    INTEGER PRIMARY KEY AUTOINCREMENT → BIGINT GENERATED BY DEFAULT AS IDENTITY
    TEXT / INTEGER              →  VARCHAR(n) / TIMESTAMPTZ / SMALLINT / BOOLEAN

두 정의가 갈리면 `CREATE TABLE IF NOT EXISTS` 가 조용히 건너뛰어 **조회 단계에 가서야
드러난다.** `tests/test_raw_db_dialects.py` 가 두 판을 대조한다.

시각은 전부 **오프셋이 붙은 ISO 문자열**로 넣는다 — 오프셋 없이 넣으면 TIMESTAMPTZ 인 운영
컬럼에서 어느 지역 시각인지 알 수 없어 하루가 밀린다.
"""

